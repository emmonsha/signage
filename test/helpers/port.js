// Выбор TCP-порта для тестов.
//
// Зачем: Node-версия fetch (undici) отказывается обращаться к «запрещённым» портам из списка
// WHATWG (bad port list) — например 6000, 6665–6669, 6679, 6697, 4045. Запрос падает с
// ошибкой «bad port», хотя сервер исправно слушает и curl отвечает 200. Тесты, которые брали
// случайный порт из широкого диапазона, изредка натыкались на такой порт и падали редко и
// загадочно («сервер не поднялся», а в логе всё хорошо).
//
// Поэтому порт берём случайно, но только из НЕзапрещённых значений диапазона.
const BLOCKED = new Set([
    1, 7, 9, 11, 13, 15, 17, 19, 20, 21, 22, 23, 25, 37, 42, 43, 53, 69, 77, 79, 87, 95,
    101, 102, 103, 104, 109, 110, 111, 113, 115, 117, 119, 123, 135, 137, 139, 143, 161, 179,
    389, 427, 465, 512, 513, 514, 515, 526, 530, 531, 532, 540, 548, 554, 556, 563, 587, 601,
    636, 989, 990, 993, 995, 1719, 1720, 1723, 2049, 3659, 4045, 4190, 5060, 5061, 6000, 6566,
    6665, 6666, 6667, 6668, 6669, 6679, 6697, 10080,
]);

const isBlocked = port => BLOCKED.has(Number(port));

// Случайный порт из [base, base+span), пропуская запрещённые для fetch значения.
function portIn(base, span = 100) {
    const free = [];
    for (let p = base; p < base + span; p++) if (!isBlocked(p)) free.push(p);
    if (!free.length) throw new Error(`нет свободных портов в диапазоне ${base}..${base + span - 1}`);
    return free[Math.floor(Math.random() * free.length)];
}

module.exports = { portIn, isBlocked, BLOCKED };
